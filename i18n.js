// Translation function with RTL handling
function translate(lang) {
  const scrollPosition = window.scrollY;

  // Update document direction and lang attribute
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

  // Optionally, add a class to body for direction-specific styling
  document.body.classList.toggle('rtl', lang === 'ar');
  document.body.classList.toggle('ltr', lang !== 'ar');

  // Apply translations to all elements with data-i18n
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang]?.[key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update button states
  document.querySelectorAll('.language-switcher .lang-btn').forEach(btn => {
    btn.classList.remove('active');
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    }
  });

  // Save preference
  localStorage.setItem("lang", lang);

  // Restore scroll position
  window.scrollTo(0, scrollPosition);
}

// Ensure DOM is ready before running translation logic
document.addEventListener('DOMContentLoaded', function() {
  const currentLang = localStorage.getItem("lang") ||
    navigator.language.split('-')[0] ||
    'ar';
  translate(currentLang);

  // Language switcher event listener
  document.querySelectorAll('.language-switcher .btn, .language-switcher .lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang') || btn.getAttribute('data-i18n').replace('lang_', '');
      localStorage.setItem("lang", lang);
      location.reload(); // Refresh the page on language change
    });
  });
});